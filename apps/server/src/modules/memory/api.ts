import { and, eq, sql } from "drizzle-orm";
import type { MemoryCandidateRecord, MemoryRecord, MemoryStats } from "@eva/shared";

import type { AppDatabase } from "../../db/index.js";
import { memories, memoryCategories } from "../../db/schema.js";
import type { DrizzleMemoryRepository, Memory } from "./memory-repository.js";
import type { MemoryExtractionRepository } from "./memory-extraction-repository.js";


export type MemoryCategory = (typeof memoryCategories)[number];

/** 落库行 → 线协议。`sourceSessionId` 在对外契约里叫 `sourceThreadId`(UI 说「会话」)。 */
const toRecord = (memory: Memory): MemoryRecord => ({
  id: memory.id,
  category: memory.category,
  origin: memory.origin,
  content: memory.content,
  metadata: memory.metadata,
  scopeKey: memory.scopeKey as MemoryRecord["scopeKey"],
  memoryKey: memory.memoryKey,
  status: memory.status,
  sourceThreadId: memory.sourceSessionId,
  sourceMessageId: memory.sourceMessageId,
  sourceRunId: memory.sourceRunId,
  confidence: memory.confidence,
  createdAt: memory.createdAt,
  updatedAt: memory.updatedAt
});

export interface MemoryApi {
  list(): readonly MemoryRecord[];
  search(query: string): readonly MemoryRecord[];
  /** Save an explicit memory without auxiliary model calls. */
  add(content: string, category?: MemoryCategory): MemoryRecord;
  update(id: string, content: string, category?: MemoryCategory): MemoryRecord | undefined;
  delete(id: string): boolean;
  stats(): MemoryStats;
  listCandidates(): readonly MemoryCandidateRecord[];
  acceptCandidate(id: string): MemoryCandidateRecord | undefined;
  rejectCandidate(id: string): MemoryCandidateRecord | undefined;
}

export const createMemoryApi = (deps: {
  readonly db: AppDatabase;
  readonly memories: DrizzleMemoryRepository;
  readonly extraction: MemoryExtractionRepository;
}): MemoryApi => {
  return {
    list: () => deps.memories.listAll().map(toRecord),

    search: (query) => deps.memories.search(query).map(toRecord),

    add: (content, category) => {
      const memory = deps.memories.save({
        id: crypto.randomUUID(),
        content,
        origin: "manual",
        ...(category !== undefined ? { category } : {})
      });

      return toRecord(memory);
    },

    update: (id, content, category) => {
      const updated = deps.memories.update(id, content, category);
      return updated ? toRecord(updated) : undefined;
    },

    delete: (id) => deps.memories.deleteById(id),

    stats: () => {
      const total = Number(
        deps.db
          .select({ count: sql<number>`count(*)` })
          .from(memories)
          .where(and(eq(memories.userId, "default"), eq(memories.status, "active")))
          .get()?.count ?? 0
      );

      const byCategory = Object.fromEntries(
        memoryCategories.map((category) => [category, 0])
      ) as Record<MemoryCategory, number>;

      for (const row of deps.db
        .select({ category: memories.category, count: sql<number>`count(*)` })
        .from(memories)
        .where(and(eq(memories.userId, "default"), eq(memories.status, "active")))
        .groupBy(memories.category)
        .all()) {
        byCategory[row.category] = Number(row.count ?? 0);
      }

      let autoGenerated = 0;
      let manualAdded = 0;
      for (const row of deps.db
        .select({ origin: memories.origin, count: sql<number>`count(*)` })
        .from(memories)
        .where(and(eq(memories.userId, "default"), eq(memories.status, "active")))
        .groupBy(memories.origin)
        .all()) {
        if (row.origin === "manual") manualAdded = Number(row.count ?? 0);
        else autoGenerated += Number(row.count ?? 0);
      }

      return {
        count: total,
        autoGenerated,
        manualAdded,
        byCategory
      };
    },

    listCandidates: () => deps.extraction.listCandidates(),
    acceptCandidate: (id) => deps.extraction.acceptCandidate(id, deps.memories),
    rejectCandidate: (id) => deps.extraction.rejectCandidate(id)
  };
};
